/**
 * SIMULATED funding engine. No bank, wallet, insurer or payment gateway is
 * connected anywhere in this codebase; an "allocation" is a database record.
 *
 * Rule: IF forecast is valid and fresh AND total >= threshold AND policy is
 * active AND simulated budget is sufficient AND the event has no allocation yet
 * THEN record one simulated allocation. Otherwise record why not.
 */

export class NotFoundError extends Error {}

type Tx = Parameters<Parameters<typeof db.transaction>[0]>[0];

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
export function isSessionId(value: string): boolean {
  return UUID_RE.test(value);
}

export function pkr(amount: number): string {
  return `PKR ${amount.toLocaleString("en-US")}`;
}

export function getPolicy(): Policy {
  const p = config.policy;
  return {
    id: p.id,
    name: p.name,
    areaId: p.areaId,
    thresholdMm: p.thresholdMm,
    windowHours: p.windowHours,
    allocationPkr: p.allocationPkr,
    initialBudgetPkr: p.initialBudgetPkr,
    active: p.active,
    simulated: true,
    disclaimer:
      "Example rule for demonstration. The threshold is not a validated flood warning, heavy rainfall does not guarantee flooding, and all funding is simulated.",
  };
}

/** Sessions isolate demo state. The ID is generated by the server and is NOT authentication. */
export async function createSession(): Promise<string> {
  await ensureSchema();
  const id = randomUUID();
  const budget = config.policy.initialBudgetPkr;
  await db.transaction(async (tx) => {
    await tx.insert(sessions).values({ id, mode: "live", budgetPkr: budget, initialBudgetPkr: budget });
    await tx.insert(auditRecords).values({
      sessionId: id,
      type: "session_created",
      message: `Session created in LIVE mode with a simulated budget of ${pkr(budget)}.`,
      details: { policyId: config.policy.id, simulated: true },
    });
  });
  return id;
}

/**
 * Stable, backend-managed event ID. This is a hackathon demonstration
 * mechanism, not a validated way of identifying real storms.
 *  - Demo: one event per scenario per session.
 *  - Live: an existing live allocation whose 24 h window still overlaps the
 *    current window keeps its event ID; otherwise the ID is the UTC date on
 *    which the forecast window starts.
 */
async function resolveEventId(tx: Tx, sessionId: string, forecast: Forecast): Promise<string> {
  if (forecast.dataKind === "demo") return `DEMO-${String(forecast.scenarioId).toUpperCase()}`;
  const windowStart = new Date(forecast.windowStart as string);
  const [overlap] = await tx
    .select({ eventId: allocations.eventId })
    .from(allocations)
    .where(and(eq(allocations.sessionId, sessionId), eq(allocations.mode, "live"), gt(allocations.windowEnd, windowStart)))
    .orderBy(desc(allocations.id))
    .limit(1);
  if (overlap) return overlap.eventId;
  return `LIVE-KARACHI-${(forecast.windowStart as string).slice(0, 10).replace(/-/g, "")}`;
}

function sameInstant(a: Date | null, b: string | null): boolean {
  if (a === null || b === null) return a === null && b === null;
  return a.getTime() === new Date(b).getTime();
}

export type EvaluationOutcome =
  | { status: DecisionStatus | "skipped"; recorded: boolean }
  | { status: DecisionStatus; recorded: true; decision: Decision; audit: AuditRecord; budgetBeforePkr: number; budgetAfterPkr: number };

/**
 * Evaluate the rule for one session. The session row is locked for the whole
 * transaction, the allocation insert is guarded by a unique constraint on
 * (session, policy, event), and the budget deduction happens in the same
 * transaction, so repeated or concurrent requests cannot double-allocate.
 */
export async function evaluateForecast(
  sessionId: string,
  forecast: Forecast,
  opts: { trigger: EvaluationTrigger; dedupe?: boolean; guardCaseId?: string },
): Promise<EvaluationOutcome> {
  await ensureSchema();
  const p = config.policy;
  return db.transaction(async (tx) => {
    const [session] = await tx.select().from(sessions).where(eq(sessions.id, sessionId)).for("update");
    if (!session) throw new NotFoundError("Session not found.");
    if (opts.trigger === "scheduler" && session.mode !== "live") return { status: "skipped", recorded: false };

    const mode: SessionMode = forecast.dataKind;
    const label = mode === "demo" ? "DEMO" : "LIVE";
    const total = forecast.totalMm;
    let status: DecisionStatus;
    let reason: string;
    let eventId: string | null = null;
    let allocationId: number | null = null;
    let budgetAfter = session.budgetPkr;

    const guard = forecast.guard;
    const guardTest = opts.trigger === "guard-test";
    if (guard && (guard.canTriggerFunding !== true || guard.status !== "accepted")) {
      status = "cannot_evaluate";
      const reasons = guard.reasons.map((item) => `${item.code}: ${item.message}`).join(" ");
      reason = `Guard verdict: ${guard.status}. ${reasons} No allocation was made.`;
    } else if (forecast.status !== "fresh" || total === null || !Number.isFinite(total) || total < 0 || !forecast.windowStart || !forecast.windowEnd) {
      status = "cannot_evaluate";
      reason = `Cannot evaluate: forecast data is ${forecast.status}. ${forecast.statusReason} No allocation was made.`;
    } else if (!guard) {
      status = "cannot_evaluate";
      reason = "Cannot evaluate: the forecast has no validation verdict. No allocation was made.";
    } else if (!p.active) {
      status = "policy_inactive";
      reason = "The funding policy is not active. No allocation was made.";
    } else if (guardTest) {
      status = total < p.thresholdMm ? "below_threshold" : "cannot_evaluate";
      reason = total < p.thresholdMm
        ? `Guard accepted the control input. Its ${total} mm total is below the ${p.thresholdMm} mm example threshold. No allocation was made.`
        : "Guard test inputs are ineligible for simulated allocations.";
    } else {
      eventId = await resolveEventId(tx, sessionId, forecast);
      if (total < p.thresholdMm) {
        status = "below_threshold";
        reason = `Forecast rainfall ${total} mm is below the ${p.thresholdMm} mm example threshold. No allocation was made.`;
      } else {
        const [existing] = await tx
          .select({ id: allocations.id })
          .from(allocations)
          .where(and(eq(allocations.sessionId, sessionId), eq(allocations.policyId, p.id), eq(allocations.eventId, eventId)))
          .limit(1);
        if (existing) {
          status = "already_allocated";
          allocationId = existing.id;
          reason = `Forecast rainfall ${total} mm meets the ${p.thresholdMm} mm example threshold, but event ${eventId} already has a simulated allocation. No second allocation was made.`;
        } else if (session.budgetPkr < p.allocationPkr) {
          status = "insufficient_budget";
          reason = `Forecast rainfall ${total} mm meets the ${p.thresholdMm} mm example threshold, but the simulated budget (${pkr(session.budgetPkr)}) is below the allocation amount (${pkr(p.allocationPkr)}). No allocation was made.`;
        } else {
          const inserted = await tx
            .insert(allocations)
            .values({
              sessionId,
              policyId: p.id,
              eventId,
              amountPkr: p.allocationPkr,
              forecastTotalMm: total,
              mode,
              scenarioId: forecast.scenarioId,
              windowStart: new Date(forecast.windowStart),
              windowEnd: new Date(forecast.windowEnd),
            })
            .onConflictDoNothing()
            .returning({ id: allocations.id });
          if (inserted.length === 0) {
            status = "already_allocated";
            reason = `Event ${eventId} already has a simulated allocation. No second allocation was made.`;
          } else {
            const updated = await tx
              .update(sessions)
              .set({ budgetPkr: sql`${sessions.budgetPkr} - ${p.allocationPkr}` })
              .where(and(eq(sessions.id, sessionId), gte(sessions.budgetPkr, p.allocationPkr)))
              .returning({ budgetPkr: sessions.budgetPkr });
            if (updated.length === 0) throw new Error("Budget changed during allocation; transaction rolled back.");
            budgetAfter = updated[0].budgetPkr;
            allocationId = inserted[0].id;
            status = "allocated";
            reason = `Forecast rainfall ${total} mm meets the ${p.thresholdMm} mm example threshold with fresh data. One SIMULATED allocation of ${pkr(p.allocationPkr)} was recorded for event ${eventId}.`;
          }
        }
      }
    }

    if (opts.dedupe && (!guard || guard.canTriggerFunding)) {
      const [last] = await tx
        .select()
        .from(evaluations)
        .where(and(eq(evaluations.sessionId, sessionId), ne(evaluations.trigger, "guard-test")))
        .orderBy(desc(evaluations.id))
        .limit(1);
      if (
        last &&
        last.mode === mode &&
        last.status === status &&
        last.eventId === eventId &&
        last.dataStatus === forecast.status &&
        sameInstant(last.modelRunAt, forecast.modelRunAt)
      ) {
        return { status, recorded: false };
      }
    }

    const now = new Date();
    const [evaluation] = await tx.insert(evaluations).values({
      sessionId,
      mode,
      scenarioId: forecast.scenarioId,
      trigger: opts.trigger,
      status,
      reason,
      eventId,
      dataStatus: forecast.status,
      forecastTotalMm: total,
      thresholdMm: p.thresholdMm,
      modelRunAt: forecast.modelRunAt ? new Date(forecast.modelRunAt) : null,
      windowStart: forecast.windowStart ? new Date(forecast.windowStart) : null,
      windowEnd: forecast.windowEnd ? new Date(forecast.windowEnd) : null,
      allocationId,
      createdAt: now,
    }).returning();
    const details = {
      decision: status,
      trigger: opts.trigger,
      guardCaseId: opts.guardCaseId,
      guard,
      eventId,
      rule: { policyId: p.id, thresholdMm: p.thresholdMm, allocationPkr: p.allocationPkr, policyActive: p.active },
      forecast: {
        dataKind: forecast.dataKind,
        scenarioId: forecast.scenarioId,
        source: forecast.source,
        model: forecast.model,
        status: forecast.status,
        totalMm: total,
        modelRunAt: forecast.modelRunAt,
        providerAvailableAt: forecast.providerAvailableAt,
        retrievedAt: forecast.retrievedAt,
        windowStart: forecast.windowStart,
        windowEnd: forecast.windowEnd,
      },
      budgetBeforePkr: session.budgetPkr,
      budgetAfterPkr: budgetAfter,
      simulated: true,
    };
    const [audit] = await tx.insert(auditRecords).values({
      sessionId,
      type: "evaluation",
      message: `${label} check (${opts.trigger}): ${reason}`,
      details,
      createdAt: now,
    }).returning();
    if (status === "allocated") {
      await tx.insert(auditRecords).values({
        sessionId,
        type: "simulated_allocation",
        message: `SIMULATED allocation #${allocationId} of ${pkr(p.allocationPkr)} recorded. Simulated budget ${pkr(session.budgetPkr)} → ${pkr(budgetAfter)}. No real money moved.`,
        details: { allocationId, eventId, amountPkr: p.allocationPkr, budgetBeforePkr: session.budgetPkr, budgetAfterPkr: budgetAfter, simulated: true },
        createdAt: now,
      });
    }
    if (!guardTest) await tx
      .update(sessions)
      .set({
        mode,
        scenarioId: forecast.scenarioId,
        lastForecast: mode === "demo" ? forecast : null,
        updatedAt: now,
        ...(opts.trigger === "scheduler" ? {} : { lastActiveAt: now }),
      })
      .where(eq(sessions.id, sessionId));
    if (guardTest) {
      return { status, recorded: true, decision: toDecision(evaluation), audit: toAudit(audit), budgetBeforePkr: session.budgetPkr, budgetAfterPkr: budgetAfter };
    }
    return { status, recorded: true };
  });
}

/** Restore one session: budget back to full, allocations and evaluations cleared. The audit trail is kept. */
export async function resetSession(sessionId: string): Promise<void> {
  await ensureSchema();
  await db.transaction(async (tx) => {
    const [session] = await tx.select().from(sessions).where(eq(sessions.id, sessionId)).for("update");
    if (!session) throw new NotFoundError("Session not found.");
    const removed = await tx.delete(allocations).where(eq(allocations.sessionId, sessionId)).returning({ id: allocations.id });
    await tx.delete(evaluations).where(eq(evaluations.sessionId, sessionId));
    const now = new Date();
    await tx
      .update(sessions)
      .set({ mode: "live", scenarioId: null, lastForecast: null, budgetPkr: session.initialBudgetPkr, updatedAt: now, lastActiveAt: now })
      .where(eq(sessions.id, sessionId));
    await tx.insert(auditRecords).values({
      sessionId,
      type: "session_reset",
      message: `Session reset: ${removed.length} simulated allocation(s) cleared and simulated budget restored to ${pkr(session.initialBudgetPkr)}. Mode returned to LIVE.`,
      details: { clearedAllocations: removed.length, budgetBeforePkr: session.budgetPkr, budgetAfterPkr: session.initialBudgetPkr },
      createdAt: now,
    });
  });
}

export async function getSchedulerStatus(): Promise<SchedulerStatus> {
  await ensureSchema();
  const [row] = await db.select().from(schedulerState).where(eq(schedulerState.id, 1)).limit(1);
  return {
    enabled: config.liveSchedulerEnabled,
    intervalMinutes: config.liveRefreshMinutes,
    lastRunAt: row?.lastRunAt?.toISOString() ?? null,
    lastSuccessAt: row?.lastSuccessAt?.toISOString() ?? null,
    lastError: row?.lastError ?? null,
    lastErrorAt: row?.lastErrorAt?.toISOString() ?? null,
    sessionsChecked: row?.sessionsChecked ?? 0,
    note: "In-process timer: it only runs while this server process is running and is not a multi-worker production scheduler.",
  };
}

function toAudit(r: typeof auditRecords.$inferSelect): AuditRecord {
  return {
    id: r.id,
    type: r.type,
    message: r.message,
    details: (r.details as Record<string, unknown> | null) ?? null,
    createdAt: r.createdAt.toISOString(),
  };
}

function toDecision(r: typeof evaluations.$inferSelect): Decision {
  return {
    id: r.id,
    status: r.status as DecisionStatus,
    reason: r.reason,
    evaluatedAt: r.createdAt.toISOString(),
    trigger: r.trigger as EvaluationTrigger,
    mode: r.mode as SessionMode,
    scenarioId: r.scenarioId,
    eventId: r.eventId,
    dataStatus: r.dataStatus as DataStatus,
    forecastTotalMm: r.forecastTotalMm,
    thresholdMm: r.thresholdMm,
    modelRunAt: r.modelRunAt?.toISOString() ?? null,
    windowStart: r.windowStart?.toISOString() ?? null,
    windowEnd: r.windowEnd?.toISOString() ?? null,
    allocationId: r.allocationId,
  };
}

export async function listAudit(sessionId: string, limit = 200): Promise<AuditRecord[]> {
  await ensureSchema();
  const [session] = await db.select({ id: sessions.id }).from(sessions).where(eq(sessions.id, sessionId)).limit(1);
  if (!session) throw new NotFoundError("Session not found.");
  const rows = await db.select().from(auditRecords).where(eq(auditRecords.sessionId, sessionId)).orderBy(desc(auditRecords.id)).limit(limit);
  return rows.map(toAudit);
}

/** Aggregate existing simulated allocations without evaluating weather or updating the session. */
export async function getSessionSpend(sessionId: string) {
  const [row] = await db.select({ allocationCount: count(allocations.id), spent: sum(allocations.amountPkr) })
    .from(sessions)
    .leftJoin(allocations, eq(allocations.sessionId, sessions.id))
    .where(eq(sessions.id, sessionId))
    .groupBy(sessions.id);
  if (!row) throw new NotFoundError("Session not found.");
  return { allocationCount: row.allocationCount, simulatedSpendPkr: Number(row.spent ?? 0) };
}

/**
 * Read-only dashboard snapshot. This function performs no writes, so GET
 * requests can never create an allocation.
 */
export async function buildDashboard(sessionId: string, opts: { liveForecast?: Forecast } = {}): Promise<Dashboard> {
  await ensureSchema();
  const [session] = await db.select().from(sessions).where(eq(sessions.id, sessionId)).limit(1);
  if (!session) throw new NotFoundError("Session not found.");
  const [allocRows, evalRows, auditRows, scheduler, [latestRow]] = await Promise.all([
    db.select().from(allocations).where(eq(allocations.sessionId, sessionId)).orderBy(desc(allocations.id)),
    db.select().from(evaluations).where(eq(evaluations.sessionId, sessionId)).orderBy(desc(evaluations.id)).limit(20),
    db.select().from(auditRecords).where(eq(auditRecords.sessionId, sessionId)).orderBy(desc(auditRecords.id)).limit(60),
    getSchedulerStatus(),
    db.select().from(evaluations).where(and(eq(evaluations.sessionId, sessionId), ne(evaluations.trigger, "guard-test"))).orderBy(desc(evaluations.id)).limit(1),
  ]);

  const mode = session.mode as SessionMode;
  const forecast: Forecast =
    mode === "demo" && session.lastForecast ? (session.lastForecast as Forecast) : (opts.liveForecast ?? (await getLiveForecast()));

  const allocs: Allocation[] = allocRows.map((a) => ({
    id: a.id,
    eventId: a.eventId,
    policyId: a.policyId,
    amountPkr: a.amountPkr,
    forecastTotalMm: a.forecastTotalMm,
    mode: a.mode as SessionMode,
    scenarioId: a.scenarioId,
    windowStart: a.windowStart.toISOString(),
    windowEnd: a.windowEnd.toISOString(),
    createdAt: a.createdAt.toISOString(),
    simulated: true,
  }));
  const decisions = evalRows.map(toDecision);
  const latest = latestRow ? toDecision(latestRow) : null;
  const decision = latest && latest.mode === mode && latest.scenarioId === session.scenarioId ? latest : null;

  return {
    sessionId,
    mode,
    scenarioId: session.scenarioId,
    area: { ...config.area },
    policy: getPolicy(),
    forecast,
    guard: forecast.guard,
    decision,
    budget: {
      currency: "PKR",
      initialPkr: session.initialBudgetPkr,
      remainingPkr: session.budgetPkr,
      allocatedPkr: allocs.reduce((sum, a) => sum + a.amountPkr, 0),
      allocationCount: allocs.length,
      simulated: true,
    },
    allocations: allocs,
    evaluations: decisions,
    audit: auditRows.map(toAudit),
    scenarios: listScenarios(),
    scheduler,
    generatedAt: new Date().toISOString(),
  };
}
